import { Hono } from "hono";
import { trpcServer } from "@hono/trpc-server";
import { setCookie, deleteCookie } from "hono/cookie";
import { and, eq } from "drizzle-orm";
import { appRouter } from "./routers";
import { createContext, OTURUM_CEREZI } from "./trpc";
import { db, newId } from "./db";
import { diagnosisRequests, invites, sessions, users, workspaceMembers } from "./schema";
import { raporPdf } from "./pdf";
import { envYukle } from "./config";
import { ipNormallestir } from "./guvenlik";
import { anahtarDogruMu, yedekAcikMi, yedekIndir, yedekOzet } from "./yedek";

envYukle();

const OTURUM_SURESI = 1000 * 60 * 60 * 24 * 14; // 14 days
// Üretim modu: KONUM_ENV=production → çerez yalnız HTTPS'te gider (Caddy arkasında)
const URETIM = process.env.KONUM_ENV === "production";

// /giris kaba kuvvet koruması: IP başına 10 deneme / 10 dk (bellek içi; yeniden başlatmada sıfırlanır — pilot için yeterli)
const GIRIS_LIMIT = 10;
const GIRIS_PENCERE = 1000 * 60 * 10;
const girisDenemeleri = new Map<string, { sayi: number; sifirla: number }>();

function girisHizSiniri(ip: string): boolean {
  const simdi = Date.now();
  const anahtar = ipNormallestir(ip);
  const k = girisDenemeleri.get(anahtar);
  if (!k || k.sifirla < simdi) {
    girisDenemeleri.set(anahtar, { sayi: 1, sifirla: simdi + GIRIS_PENCERE });
    return true;
  }
  k.sayi += 1;
  // bellek şişmesin: penceresi dolmuş eski kayıtları ara sıra süpür
  if (girisDenemeleri.size > 5000) {
    for (const [a, v] of girisDenemeleri) if (v.sifirla < simdi) girisDenemeleri.delete(a);
  }
  return k.sayi <= GIRIS_LIMIT;
}

// Local development seed: a single invite is generated on first launch (documented in README).
// In production, invites will be generated by the platform owner from the Agency Console.
function tohumlama() {
  const varMi = db.select().from(invites).all();
  if (varMi.length === 0) {
    db.insert(invites)
      .values({
        id: newId("inv"),
        eposta: process.env.KONUM_PLATFORM_SAHIBI || "cem@konum.local",
        rol: "sahip",
        workspaceId: null,
        token: process.env.KONUM_PILOT_DAVET || "KONUM-PILOT-1",
        sonKullanma: Date.now() + 1000 * 60 * 60 * 24 * 365,
        kullanildi: 0,
        createdAt: Date.now(),
      })
      .run();
  }
}

export function createServerApp(): Hono {
  tohumlama();
  const app = new Hono();

  app.get("/health", (c) => c.json({ ok: true, servis: "konum-api" }));

  // Sign-in: email + invite code (local equivalent of Kimi OAuth — v2 update 4)
  app.post("/giris", async (c) => {
    const ip =
      c.req.header("x-forwarded-for")?.split(",")[0]?.trim() || c.req.header("x-real-ip") || "yerel";
    if (!girisHizSiniri(ip)) {
      return c.json({ hata: "Too many sign-in attempts. Wait 10 minutes and try again." }, 429);
    }
    const govde = await c.req.json().catch(() => null);
    const eposta = String(govde?.eposta ?? "").trim().toLocaleLowerCase("en");
    const kod = String(govde?.davetKodu ?? "").trim();
    if (!eposta || !kod) {
      return c.json({ hata: "Email and invite code are required." }, 400);
    }
    const davet = db.select().from(invites).where(eq(invites.token, kod)).get();
    if (!davet || davet.sonKullanma < Date.now() || davet.eposta.toLocaleLowerCase("en") !== eposta) {
      return c.json({ hata: "This invite code is not valid for this email. If you don't have an invite, contact the platform owner." }, 403);
    }
    let user = db.select().from(users).where(eq(users.email, eposta)).get();
    // Invites are single-use; however, a user whose account is already created can sign in
    // again with the same email + invite code (local development equivalent — README).
    if (davet.kullanildi === 1 && !user) {
      return c.json({ hata: "This invite code has already been used." }, 403);
    }
    if (!user) {
      user = { id: newId("usr"), email: eposta, name: eposta.split("@")[0], createdAt: Date.now() };
      db.insert(users).values(user).run();
    }
    db.update(invites).set({ kullanildi: 1 }).where(eq(invites.id, davet.id)).run();
    if (davet.workspaceId) {
      const uyeMi = db
        .select()
        .from(workspaceMembers)
        .where(and(eq(workspaceMembers.workspaceId, davet.workspaceId), eq(workspaceMembers.userId, user.id)))
        .get();
      if (!uyeMi) {
        db.insert(workspaceMembers)
          .values({ id: newId("mem"), workspaceId: davet.workspaceId, userId: user.id, rol: davet.rol, createdAt: Date.now() })
          .run();
      }
    }

    const token = newId("oturum");
    db.insert(sessions)
      .values({ token, userId: user.id, createdAt: Date.now(), expiresAt: Date.now() + OTURUM_SURESI })
      .run();
    setCookie(c, OTURUM_CEREZI, token, {
      httpOnly: true,
      secure: URETIM,
      sameSite: "Lax",
      path: "/",
      maxAge: OTURUM_SURESI / 1000,
    });
    return c.json({ ok: true, kullanici: { id: user.id, email: user.email, name: user.name } });
  });

  app.post("/cikis", (c) => {
    deleteCookie(c, OTURUM_CEREZI, { path: "/" });
    return c.json({ ok: true });
  });

  // /teshis PDF raporu — herkese açık, kimlik rapor kimliğiyle (tahmin edilemez id)
  app.get("/teshis/:id{.+\\.pdf}", (c) => {
    const id = (c.req.param("id") || "").replace(/\.pdf$/, "");
    const r = db.select().from(diagnosisRequests).where(eq(diagnosisRequests.id, id)).get();
    if (!r) return c.json({ hata: "Report not found." }, 404);
    const rapor = JSON.parse(r.rapor || "{}") as {
      baslik?: string;
      anaIddia?: string;
      gucluKanitlar?: string[];
      eksikKanitlar?: string[];
      oneriler?: string[];
      skor?: number;
      mod?: string;
    };
    const pdf = raporPdf(
      "Konum — Message Map Report",
      `${r.url} · ${new Date(r.zaman).toISOString().slice(0, 10)} · Evidence score: ${rapor.skor ?? "-"} / 100`,
      [
        { baslik: "Core claim", satirlar: [rapor.anaIddia || ""] },
        { baslik: "Proof already on the page", satirlar: (rapor.gucluKanitlar?.length ? rapor.gucluKanitlar : ["No concrete proof found."]).map((x) => `- ${x}`) },
        { baslik: "Claims lacking proof", satirlar: (rapor.eksikKanitlar ?? []).map((x) => `- ${x}`) },
        { baslik: "Three suggestions", satirlar: (rapor.oneriler ?? []).map((x, i) => `${i + 1}. ${x}`) },
        {
          baslik: "Note",
          satirlar: [
            rapor.mod === "llm"
              ? "This report was generated by a live model call (claude-haiku-5-5)."
              : "SIMULATION: this report was produced without a live LLM connection; treat it as a demo of the format, not a real analysis.",
            "Konum — the agent-powered continuous marketing operating system. An AIWork School company.",
          ],
        },
      ],
      // Danışma turu 2: etiket her sayfada filigran — ekran görüntüsüyle bile atlatılamaz
      rapor.mod === "llm" ? undefined : "SIMULATION — NOT A LIVE ANALYSIS · konum",
    );
    return new Response(pdf, {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="konum-message-map-${id}.pdf"`,
      },
    });
  });

  // Tam SQLite yedeği — kalıcı disksiz ortamlarda (Render Free) veri kurtarmanın tek yolu.
  // Yalnızca KONUM_YEDEK_ANAHTARI tanımlıysa açık; değilse 404 (uç gizli kalır), yanlış anahtar 401.
  app.get("/admin/yedek", async (c) => {
    if (!yedekAcikMi()) return c.json({ hata: "Not found." }, 404);
    if (!anahtarDogruMu(c)) return c.json({ hata: "Unauthorized." }, 401);
    const dosya = await yedekIndir();
    const damga = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
    return new Response(new Uint8Array(dosya), {
      headers: {
        "Content-Type": "application/octet-stream",
        "Content-Disposition": `attachment; filename="konum-yedek-${damga}.db"`,
      },
    });
  });

  app.get("/admin/yedek/ozet", (c) => {
    if (!yedekAcikMi()) return c.json({ hata: "Not found." }, 404);
    if (!anahtarDogruMu(c)) return c.json({ hata: "Unauthorized." }, 401);
    return c.json({ zaman: new Date().toISOString(), ...yedekOzet() });
  });

  app.use(
    "/trpc/*",
    trpcServer({
      router: appRouter,
      createContext: (opts) => createContext(opts) as unknown as Record<string, unknown>,
    }),
  );

  return app;
}
